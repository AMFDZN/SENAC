print("--------------------\nVamos comparar dois números e verificar se um número é maior ou menor que o outro")
valor1=int(input("Digite o primeiro número: "))
valor2=int(input("Digite o segundo número: "))

if valor1 < valor2:
    print(f"o número {valor1} é menor que o número {valor2}")
else:
    print(f"o número {valor2} é menor que o número {valor1}")