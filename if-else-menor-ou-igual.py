print("--------------------\nVamos comparar dois números e verificar se um número é menor ou igual ao outro, ou é maior que o outro")
numero1=int(input("Digite o primeiro número: "))
numero2=int(input("Digite o segundo número: "))

if numero1 <= numero2:
    print(f"o número {numero1} é menor ou igual ao número {numero2}")
else:
    print(f"o número {numero2} é maior que o número {numero1}")
